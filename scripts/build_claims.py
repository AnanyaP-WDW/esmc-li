#!/usr/bin/env python3
"""Generate paper/claims.tsv and docs/claims.md from the template placeholders."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "paper" / "main.template.md"
NUMBERS = json.loads((ROOT / "paper" / "numbers.json").read_text())
TSV = ROOT / "paper" / "claims.tsv"
OUT = ROOT / "docs" / "claims.md"
NUM_RE = re.compile(r"\{\{n:([^}]+)\}\}")
HEAD_RE = re.compile(r"^(#{1,4})\s+(.*)$")


def main() -> int:
    text = TEMPLATE.read_text()
    section = "(front matter)"
    rows = []
    seen = set()
    for line in text.splitlines():
        h = HEAD_RE.match(line)
        if h:
            section = h.group(2).strip()
        for key in NUM_RE.findall(line):
            if key in seen:
                continue
            seen.add(key)
            if key not in NUMBERS:
                raise SystemExit(f"unknown number key: {key}")
            n = NUMBERS[key]
            rows.append({
                "id": f"C{len(rows) + 1:02d}",
                "key": key,
                "section": section,
                "display": n["display"],
                "table": n["table"],
                "row": n["row"],
                "col": n["col"],
                "sources": ",".join(n["sources"]) if n["sources"] else "(fact)",
            })
    with TSV.open("w") as f:
        f.write("id\tkey\tsection\tdisplay\ttable\trow\tcol\tsources\n")
        for r in rows:
            f.write("\t".join(str(r[k]) for k in
                              ("id", "key", "section", "display", "table",
                               "row", "col", "sources")) + "\n")

    lines = [
        "# M9 claims audit",
        "",
        "Generated by `make claims` from `paper/main.template.md` and",
        "`paper/numbers.json`. Every numeric sentence in the paper is a",
        "`{{n:key}}` placeholder; each key maps to one generated table cell.",
        "",
        "## Prior work framing",
        "",
        "ProtoCol introduced residue-level late interaction for",
        "protein homolog search. This paper does **not** claim that model idea.",
        "The contributions are the deployment-shaped full-length benchmark, the",
        "ESM-C training ablation, the index/search systems measurements, and",
        "the open-source package. This statement is a manual sign-off, recorded",
        "here rather than automated.",
        "",
        "## Numeric claims",
        "",
        f"Coverage: **{len(rows)}/{len(rows)}** numeric placeholders mapped to a",
        "generated table cell.",
        "",
        "| ID | Section | Value | Table | Row | Column | Source |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['id']} | {r['section']} | {r['display']} | {r['table']} | "
            f"{r['row']} | {r['col']} | `{r['sources']}` |")
    lines += [
        "",
        "## Table provenance",
        "",
        "Every table in `paper/tables/` is generated by `scripts/paper_assets.py`",
        "from `paper/results.lock.json`; the lock is verified against",
        "`results/runs.jsonl` at the pinned results commit by",
        "`scripts/verify_lock.py`. Table cells carry no hand-copied numbers.",
        "",
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"claims: {len(rows)}/{len(rows)} mapped -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
